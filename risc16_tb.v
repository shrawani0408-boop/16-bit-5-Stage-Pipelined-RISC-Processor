`timescale 1ns / 1ps

module risc16_tb;

    // =========================================================
    // CLOCK AND RESET
    // =========================================================

    reg clk;
    reg reset;


    // =========================================================
    // PROCESSOR
    // =========================================================

    risc16_pipeline DUT(
        .clk(clk),
        .reset(reset)
    );


    // =========================================================
    // CLOCK GENERATION
    // =========================================================

    initial begin

        clk = 1'b0;

        forever #5 clk = ~clk;

    end


    // =========================================================
    // TEST
    // =========================================================

    initial begin

        // Reset processor
        reset = 1'b1;

        #20;

        reset = 1'b0;

        // Run processor
        #200;
 
        $finish;

    end

endmodule 